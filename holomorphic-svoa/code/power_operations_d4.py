"""S5 check: Sym^2 o Sym^2 equals the D_4 = Z_2 wr Z_2 orbifold of the 4th power (constant partition function Z = I).

For a commuting pair (a, b) in D_4 < S_4, the 4-fold cover of T^2 has one component per orbit of <a, b> on {0,1,2,3};
each component contributes Z(lattice) = I for constant Z.  So eps_{D_4}(P_4(I)) = (1/8) sum eps(a,b) I^{#orbits}.
The outer Arf twist: eps(a,b) = -1 iff the Z_2-bundle on T^2 obtained by projecting (a,b) along the outer
homomorphism D_4 -> D_4/(Z_2 x Z_2) = Z_2 is nontrivial.  Tested: plain/plain and plain-inner/Arf-outer.
Run: .venv/bin/python claude/paper/power_operations_d4.py
"""
from itertools import permutations
from fractions import Fraction as F

def comp(p, q):            # (p o q)(i) = p[q[i]]
    return tuple(p[q[i]] for i in range(4))

# D_4 = Z_2 wr Z_2 acting on {0,1 | 2,3}: generated by (01), (23), (02)(13)
gens = [(1, 0, 2, 3), (0, 1, 3, 2), (2, 3, 0, 1)]
G = {tuple(range(4))}
while True:
    new = {comp(g, h) for g in G for h in gens} | G
    if new == G: break
    G = new
assert len(G) == 8
outer = lambda p: 0 if p[0] in (0, 1) else 1          # does p swap the two blocks?

def orbits(a, b):
    seen, n = set(), 0
    for x in range(4):
        if x in seen: continue
        n += 1; stack = [x]
        while stack:
            y = stack.pop()
            if y in seen: continue
            seen.add(y); stack += [a[y], b[y]]
    return n

def d4_orbifold(I, arf_outer):
    tot = F(0)
    for a in G:
        for b in G:
            if comp(a, b) != comp(b, a): continue
            sign = -1 if (arf_outer and (outer(a) or outer(b))) else 1
            tot += sign * F(I) ** orbits(a, b)
    return tot / 8

sym2 = lambda I: F(I * I + 3 * I, 2)
sym2_arf = lambda I: F(I * I - 3 * I, 2)
for I in range(-6, 7):
    assert d4_orbifold(I, False) == sym2(sym2(I)), I
    assert d4_orbifold(I, True) == sym2_arf(sym2(I)), I
print("D_4 orbifold of P_4(I) = Sym2(Sym2(I)) and, with the outer Arf sign, Sym2_Arf(Sym2(I)), for I = -6..6: True")
print("I = -4:  plain/plain ->", d4_orbifold(-4, False), "  plain/Arf ->", d4_orbifold(-4, True))
print("commuting pairs in D_4:", sum(1 for a in G for b in G if comp(a, b) == comp(b, a)))
