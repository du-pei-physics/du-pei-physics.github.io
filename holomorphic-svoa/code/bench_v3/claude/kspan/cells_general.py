"""General transfer cells of even size q, their indices for every ring length L, and the
GJF Theorem 5.6 conditions for every k = qL/6.

A cell is (Q, S, r): Q orthogonal, S anti-orthogonal (q x q over F_3), the first r
coordinates of aQ delayed.  Local table
    T[p, v] = sum_{a in {1,2}^q, (aQ)_{<r} = v} phi(a) phi((p, (aQ)_{>=r}) S).
Ring of L cells: negacyclic (z^L = -1) index I_L = Tr(J T^L); cyclic (z^L = +1) index
C_L = Tr(T^L).  Both are self-dual codes of length 2qL = 12k, k = qL/6.

GJF needs an automorphism g of order m = gcd(k,24) with g^{m/2} = -1 (m even) and
g^{m/3} fixed-point-free of shape 3^{4k} and balanced (3 | m).  Taking g inside the group
generated by the cell shift z (and -1):
  negacyclic:  g = z^{2L/m}  (needs m | 2L, and 3 | L when 3 | m);
               balance  <=>  I_{L/3} = 0;   index  |I_L| = 24.
  cyclic:      m in {1, 3}: g = z^{L/m};  m = 2: g = -1;  m = 6: g = -z^{L/3};
               m in {4, 8, 12, 24}: no such g (z^j is a permutation, never -1);
               balance  <=>  C_{L/3} = 0;   index  |C_L| = 24.
The 2-adic theorem (k24_transfer) makes |I_L| = 24 impossible when 4 | L, so m in {8, 24}
and the negacyclic m = 4, 12 cases with 4 | L are hopeless; they are still reported.
"""
import itertools, json, time
from math import gcd
from pathlib import Path
import numpy as np
import sympy

HERE = Path(__file__).resolve().parent


# ------------------------------------------------------------------ matrices over F_3
def legendre(a, p):
    a %= p
    return 0 if a == 0 else (1 if pow(a, (p - 1) // 2, p) == 1 else -1)


def conference(p):
    """Conference matrix of order p+1 (p prime, p = 2 mod 3 so that C C^T = p I = -I)."""
    n = p + 1
    C = np.zeros((n, n), dtype=np.int64)
    skew = (p % 4 == 3)
    for i in range(n):
        for j in range(n):
            if i == j:
                C[i, j] = 0
            elif i == 0:
                C[i, j] = 1
            elif j == 0:
                C[i, j] = -1 if skew else 1
            else:
                C[i, j] = legendre(j - i, p)
    C %= 3
    assert np.array_equal((C @ C.T) % 3, (2 * np.eye(n, dtype=np.int64)) % 3)
    return C


def reflection(v):
    v = np.asarray(v, dtype=np.int64) % 3
    nn = int(v @ v) % 3
    assert nn
    return (np.eye(len(v), dtype=np.int64) - 2 * nn * np.outer(v, v)) % 3


H4 = np.array([[1, 1, 1, 1], [1, 1, 2, 2], [1, 2, 1, 2], [1, 2, 2, 1]], dtype=np.int64)
A2 = np.array([[1, 1], [1, 2]], dtype=np.int64)          # 2x2 anti-orthogonal (tetracode)
_H2 = np.array([[1, 1], [1, -1]])
H8 = (np.kron(_H2, np.kron(_H2, _H2)) % 3).astype(np.int64)   # Sylvester: H8 H8^T = 8I = -I mod 3, anti-orthogonal


def block_diag(*ms):
    n = sum(m.shape[0] for m in ms)
    out = np.zeros((n, n), dtype=np.int64); i = 0
    for m in ms:
        out[i:i + m.shape[0], i:i + m.shape[0]] = m; i += m.shape[0]
    return out


def is_orth(Q):
    return np.array_equal((Q @ Q.T) % 3, np.eye(Q.shape[0], dtype=np.int64))


def is_anti(S):
    return np.array_equal((S @ S.T) % 3, (2 * np.eye(S.shape[0], dtype=np.int64)) % 3)


def anti_bases(q):
    """Named anti-orthogonal q x q matrices."""
    out = {"A0": block_diag(*[A2] * (q // 2))}
    if sympy.isprime(q - 1) and (q - 1) % 3 == 2:
        out["conf"] = conference(q - 1)
    if q % 6 == 0:
        out["conf6blocks"] = block_diag(*[conference(5)] * (q // 6))
    if q % 12 == 0:
        out["paley12blocks"] = block_diag(*[conference(11)] * (q // 12))
    # bases for widths 8, 10, 14, 16, ... (added 18 Oct: the A0 base alone gives identically zero
    # indices in period rings; mixed-size blocks are needed)
    if q % 8 == 0:
        out["h8blocks"] = block_diag(*[H8] * (q // 8))
    if q >= 10 and q % 2 == 0 and q % 12 != 0:
        out["h8_a2"] = block_diag(H8, *[A2] * ((q - 8) // 2))
    if q >= 8 and q % 2 == 0 and q % 6 != 0:
        out["conf6_a2"] = block_diag(conference(5), *[A2] * ((q - 6) // 2))
    if q >= 14 and q % 2 == 0 and q % 12 != 0:
        out["paley12_a2"] = block_diag(conference(11), *[A2] * ((q - 12) // 2))
    if q >= 16 and q % 2 == 0:
        out["conf6_h8_a2"] = block_diag(conference(5), H8, *[A2] * ((q - 14) // 2))
    for k, m in out.items():
        assert is_anti(m), k
    return out


def hadamard_Q(q, rng, nblocks=None):
    """Hadamard 4-blocks (as many as fit, or nblocks) padded with the identity, then a
    random permutation of columns."""
    nb = q // 4 if nblocks is None else nblocks
    Q = block_diag(*([H4] * nb + [np.eye(q - 4 * nb, dtype=np.int64)] if q - 4 * nb else [H4] * nb))
    P = np.zeros((q, q), dtype=np.int64); P[np.arange(q), rng.permutation(q)] = 1
    return (Q @ P) % 3


def random_reflection(rng, q, weight=None):
    while True:
        if weight is None:
            v = rng.integers(0, 3, q)
        else:
            v = np.zeros(q, dtype=np.int64); v[rng.choice(q, weight, replace=False)] = rng.integers(1, 3, weight)
        if int(v @ v) % 3:
            return reflection(v)


# ------------------------------------------------------------------ tables and traces
def table(Q, S, r):
    """Local table T (3^r x 3^r, int64), the J-permutation neg, states."""
    q = Q.shape[0]
    a = np.array(list(itertools.product((1, 2), repeat=q)), dtype=np.int64)
    phia = (1 - 2 * (np.sum(a == 2, axis=1) % 2)).astype(np.int64)
    X = (a @ Q) % 3
    pw = 3 ** np.arange(r)
    vidx = X[:, :r] @ pw
    Uout = (X[:, r:] @ S[r:, :]) % 3                       # 2^q x q
    states = np.array(list(itertools.product(range(3), repeat=r)), dtype=np.int64)[:, ::-1]
    n = 3 ** r
    T = np.zeros((n, n), dtype=np.int64)
    Srows = S[:r, :]
    for pi in range(n):
        out = (Uout + (states[pi] @ Srows) % 3) % 3
        w = np.where(np.all(out != 0, axis=1), 1 - 2 * (np.sum(out == 2, axis=1) % 2), 0) * phia
        T[pi] = np.bincount(vidx, weights=w, minlength=n).astype(np.int64)
    neg = ((-states) % 3) @ pw
    return T, neg


_PRIMES = [int(p) for p in [sympy.prevprime(2 ** 20 - 1000 * i) for i in range(24)]]


def traces(T, neg, Lmax, bits):
    """Exact I_L = Tr(J T^L) and C_L = Tr(T^L) for L = 1..Lmax by CRT over enough primes.
    Matrix products are done in float64 (BLAS) with primes < 2^20, so every intermediate
    sum (< 3^5 * 2^40 < 2^49) is exact; int64 matmul would be ~30x slower."""
    k = bits // 19 + 2
    primes = _PRIMES[:k]
    assert T.shape[0] <= 3 ** 5
    MOD = 1
    for p in primes:
        MOD *= p
    n = T.shape[0]; idx = np.arange(n)
    resI = {L: [] for L in range(1, Lmax + 1)}; resC = {L: [] for L in range(1, Lmax + 1)}
    for p in primes:
        Tp = (T % p).astype(np.float64); M = Tp.copy()
        for L in range(1, Lmax + 1):
            if L > 1:
                M = np.fmod(np.matmul(M, Tp), p)
            resI[L].append(int(round(M[neg, idx].sum())) % p); resC[L].append(int(round(np.trace(M))) % p)
    def crt(rs):
        x = 0
        for p, r_ in zip(primes, rs):
            m = MOD // p; x = (x + r_ * m * pow(m, -1, p)) % MOD
        return x - MOD if x > MOD // 2 else x
    return {L: crt(resI[L]) for L in resI}, {L: crt(resC[L]) for L in resC}


# ------------------------------------------------------------------ GJF conditions per k
def targets(q, Lmax, kmax=24):
    """List of dicts {k, L, m, nega: (balanceL or None), cyc: (available, balanceL)}."""
    out = []
    for L in range(1, Lmax + 1):
        if (q * L) % 6:
            continue
        k = q * L // 6
        if k > kmax or k < 1:
            continue
        m = gcd(k, 24)
        nega = None
        if (2 * L) % m == 0 and (m % 3 == 0) <= (L % 3 == 0):
            nega = {"balance_L": (L // 3 if m % 3 == 0 else None)}
        cyc = None
        if m in (1, 2, 3, 6) and (m % 3 == 0) <= (L % 3 == 0):
            cyc = {"balance_L": (L // 3 if m % 3 == 0 else None)}
        out.append({"k": k, "L": L, "m": m, "target_index": 24 // m, "nega": nega, "cyc": cyc,
                    "theorem2_blocks_nega": (L % 4 == 0)})
    return out


def check(I, C, tgt):
    hits = []
    L = tgt["L"]
    if tgt["nega"] is not None and abs(I[L]) == 24:
        b = tgt["nega"]["balance_L"]
        if b is None or I[b] == 0:
            hits.append("nega")
    if tgt["cyc"] is not None and abs(C[L]) == 24:
        b = tgt["cyc"]["balance_L"]
        if b is None or C[b] == 0:
            hits.append("cyc")
    return hits


# ------------------------------------------------------------------ scanner
class Scanner:
    def __init__(self, q, Lmax, out_path, kmin_store=8, save_every=2000):
        self.q, self.Lmax = q, Lmax
        self.tgts = targets(q, Lmax)
        self.bits = q * Lmax
        self.out = Path(out_path)
        self.hits = []                       # stored only for k >= kmin_store (the open cases)
        self.hit_counts = {}                 # per target key: number of hits (all k)
        self.kmin_store, self.save_every = kmin_store, save_every
        self.minI = {L: None for L in range(1, Lmax + 1)}; self.minC = dict(self.minI)
        self.min_balanced = {}      # per target k: smallest |index| among cells satisfying balance
        self.n = 0; self.t0 = time.time()

    def feed(self, T, neg, desc):
        I, C = traces(T, neg, self.Lmax, self.bits)
        self.n += 1
        for L in range(1, self.Lmax + 1):
            for store, v in ((self.minI, I[L]), (self.minC, C[L])):
                if v and (store[L] is None or abs(v) < store[L]):
                    store[L] = abs(v)
        for t in self.tgts:
            for kind in ("nega", "cyc"):
                spec = t[kind]
                if spec is None:
                    continue
                vals = I if kind == "nega" else C
                b = spec["balance_L"]
                if b is None or vals[b] == 0:
                    v = abs(vals[t["L"]])
                    key = f"k={t['k']}/{kind}"
                    if v and (key not in self.min_balanced or v < self.min_balanced[key]):
                        self.min_balanced[key] = v
            h = check(I, C, t)
            if h:
                for kind in h:
                    key = f"k={t['k']}/{kind}"
                    self.hit_counts[key] = self.hit_counts.get(key, 0) + 1
                if t["k"] >= self.kmin_store:
                    self.hits.append({"k": t["k"], "L": t["L"], "m": t["m"], "kinds": h, "desc": desc,
                                      "I": {str(L): I[L] for L in I}, "C": {str(L): C[L] for L in C}})
        if self.n % self.save_every == 0:
            self.save()

    def save(self):
        self.out.write_text(json.dumps({"q": self.q, "Lmax": self.Lmax, "cells": self.n,
                                        "seconds": time.time() - self.t0,
                                        "targets": self.tgts, "hit_counts": self.hit_counts,
                                        "hits": self.hits,
                                        "min_nonzero_abs_I_L": self.minI, "min_nonzero_abs_C_L": self.minC,
                                        "min_balanced_abs_index_per_target": self.min_balanced},
                                       indent=1, default=str))
